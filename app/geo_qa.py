def _haversine_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlmb = math.radians(lng2 - lng1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def normalize_sido(sido: str | None) -> str | None:
    if not sido:
        return None
    key = sido.strip()
    if key in _SIDO_BBOX:
        return key
    if key in _SIDO_ALIASES:
        return _SIDO_ALIASES[key]
    for alias, norm in _SIDO_ALIASES.items():
        if key.startswith(alias[:2]) or key.startswith(norm):
            return norm
    if len(key) >= 2 and key[:2] in _SIDO_BBOX:
        return key[:2]
    return None


def sido_from_address(address: str | None) -> str | None:
    if not address:
        return None
    m = _SIDO_FROM_ADDR.match(address.strip())
    if not m:
        return None
    return normalize_sido(m.group(1))


def coords_plausible_for_row(row: dict[str, Any]) -> bool:
    """Return False when lat/lng clearly disagree with address/sido/sigungu."""
    try:
        lat = float(row["lat"])
        lng = float(row["lng"])
    except (KeyError, TypeError, ValueError):
        return False

    sido_field = normalize_sido(row.get("sido"))
    sido_addr = sido_from_address(row.get("address"))
    # Prefer address-derived sido when both exist and disagree → treat as bad data
    if sido_field and sido_addr and sido_field != sido_addr:
        return False

    sido = sido_addr or sido_field
    if sido:
        box = _SIDO_BBOX.get(sido)
        if box is not None:
            lat_min, lat_max, lng_min, lng_max = box
            if not (lat_min <= lat <= lat_max and lng_min <= lng <= lng_max):
                return False

        # Provincial address must not sit on top of a metro district
        # (e.g. 경남 양산 주소 + 부산 해운대 좌표)
        if sido not in _METRO_SIDOS:
            for (msido, _msg), cen in _CITY_CENTROID.items():
                if msido not in _METRO_SIDOS:
                    continue
                if _haversine_km(cen[0], cen[1], lat, lng) <= _METRO_DISTRICT_HIT_KM:
                    return False

    sigungu = (row.get("sigungu") or "").strip()
    if sido and sigungu:
        cen = _CITY_CENTROID.get((sido, sigungu))
        if cen is not None:
            if _haversine_km(cen[0], cen[1], lat, lng) > _CITY_MAX_KM:
                return False

    return True
